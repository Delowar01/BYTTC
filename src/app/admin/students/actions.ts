"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { z } from "zod";
import { withRole } from "@/lib/actions";
import { dbMessage, fail, formValues, success, zodFail, type FormState } from "@/lib/forms";
import { ALL_STAFF, isCentral } from "@/lib/roles";
import { normalizePhoto } from "@/lib/photos";
import { optDate, optEmail, optInt, optText, reqText, uuid } from "@/lib/schemas";

const idPattern = /^[A-Z0-9-]{3,20}$/;
const optIdent = (label: string) =>
  z
    .string()
    .optional()
    .transform((v) => (v ? v.trim().toUpperCase() : ""))
    .refine((v) => v === "" || idPattern.test(v), `${label}: 3–20 letters, digits or dashes`);

const schema = z.object({
  institute_id: uuid("Institute"),
  course_id: uuid("Course"),
  session_id: uuid("Session"),
  roll_no: optIdent("Roll number"),
  registration_no: optIdent("Registration number"),
  name_en: reqText("Name (English)", 120),
  name_bn: optText,
  father_name: optText,
  mother_name: optText,
  date_of_birth: optDate,
  gender: z.enum(["male", "female", "other", ""]).optional().transform((v) => (v ? v : null)),
  phone: optText,
  email: optEmail,
  address: optText,
  thana: optText,
  district: optText,
  national_id: optText,
  // Optional and PRIVATE: used only for secure result lookup, never displayed publicly.
  passport_no: z
    .string()
    .optional()
    .transform((v) => (v ? v.replace(/\s/g, "").toUpperCase() : null))
    .refine((v) => v === null || /^[A-Z0-9]{5,20}$/.test(v), "Passport number: 5–20 letters or digits"),
  passing_year: optInt(1950, 2100),
  enrollment_date: optDate,
  course_duration_override: optText,
  status: z.enum(["active", "completed", "dropped"]),
});

export async function saveStudent(id: string | null, _prev: FormState, formData: FormData): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase, profile }) => {
    const values = formValues(formData);
    // Tenants can only ever write to their own institute.
    if (!isCentral(profile.role)) values.institute_id = profile.institute_id ?? "";
    const parsed = schema.safeParse(values);
    if (!parsed.success) return zodFail(parsed.error, values);
    const { roll_no, registration_no, ...rest } = parsed.data;
    if (id && (!roll_no || !registration_no)) {
      return fail("Roll and registration numbers cannot be blank.", values, {
        ...(roll_no ? {} : { roll_no: "Required" }),
        ...(registration_no ? {} : { registration_no: "Required" }),
      });
    }
    // On create, blank identifiers are generated by the database
    // (roll: sequence default; registration: random, via trigger).
    const row = { ...rest, registration_no, ...(roll_no ? { roll_no } : {}) };
    const { data, error } = id
      ? await supabase.from("students").update(row).eq("id", id).select("id")
      : await supabase.from("students").insert(row).select("id");
    if (error) return fail(dbMessage(error), values);
    if (!data?.length) return fail("Student not found or not permitted.", values);
    revalidatePath("/admin/students");
    redirect(`/admin/students/${data[0].id}?saved=1`);
  });
}

export async function deleteStudent(id: string, _prev: FormState): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const { data, error } = await supabase.from("students").delete().eq("id", id).select("id");
    if (error) return fail(dbMessage(error));
    if (!data?.length) return fail("Not permitted or student not found.");
    revalidatePath("/admin/students");
    redirect("/admin/students?deleted=1");
  });
}

const DOC_TYPES = ["application/pdf", "image/jpeg", "image/png"];

async function studentFolder(supabase: Parameters<Parameters<typeof withRole>[1]>[0]["supabase"], id: string) {
  const { data } = await supabase.from("students").select("institute_id").eq("id", id).maybeSingle();
  return data ? `institutes/${data.institute_id}/students/${id}` : null;
}

/** Store a personal document privately; storage RLS limits institutes to their own folder. */
export async function uploadStudentDocument(id: string, _prev: FormState, formData: FormData): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const folder = await studentFolder(supabase, id);
    if (!folder) return fail("Student not found.");
    const file = formData.get("file");
    if (!(file instanceof File) || file.size === 0) return fail("Choose a file.");
    if (!DOC_TYPES.includes(file.type)) return fail("Only PDF, JPEG or PNG files are accepted.");
    if (file.size > 5 * 1024 * 1024) return fail("The file is larger than 5 MB.");
    const name = file.name.toLowerCase().replace(/[^a-z0-9.]+/g, "-").slice(-60);
    const { error } = await supabase.storage.from("private-documents").upload(`${folder}/${Date.now()}-${name}`, file, { contentType: file.type });
    if (error) return fail(error.message);
    await supabase.rpc("log_event", { p_action: "document.upload", p_table: "students", p_record_id: id, p_data: { name } });
    revalidatePath(`/admin/students/${id}`);
    return success("Document uploaded.");
  });
}

export async function deleteStudentDocument(id: string, name: string, _prev: FormState): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const folder = await studentFolder(supabase, id);
    if (!folder || name.includes("/")) return fail("Not found.");
    const { data, error } = await supabase.storage.from("private-documents").remove([`${folder}/${name}`]);
    if (error) return fail(error.message);
    if (!data?.length) return fail("Only central administrators can delete documents.");
    await supabase.rpc("log_event", { p_action: "document.delete", p_table: "students", p_record_id: id, p_data: { name } });
    revalidatePath(`/admin/students/${id}`);
    return success("Document deleted.");
  });
}

/** Upload or replace the student's photo (private; reused by all documents). */
export async function uploadStudentPhoto(id: string, _prev: FormState, formData: FormData): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const { data: student } = await supabase.from("students").select("institute_id").eq("id", id).maybeSingle();
    if (!student) return fail("Student not found.");
    const file = formData.get("file");
    if (!(file instanceof File) || file.size === 0) return fail("Choose a photo.");
    const photo = await normalizePhoto(file);
    if ("error" in photo) return fail(photo.error);
    // Old photo files are kept: issued documents may still reference them.
    const path = `institutes/${student.institute_id}/students/${id}/photo/${Date.now()}.jpg`;
    const { error } = await supabase.storage.from("private-documents").upload(path, photo.bytes, { contentType: "image/jpeg" });
    if (error) return fail(error.message);
    const { error: uErr } = await supabase.from("students").update({ photo_path: path }).eq("id", id);
    if (uErr) return fail(dbMessage(uErr));
    revalidatePath(`/admin/students/${id}`);
    return success("Photo saved.");
  });
}

export async function removeStudentPhoto(id: string, _prev: FormState): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const { data, error } = await supabase.from("students").update({ photo_path: null }).eq("id", id).select("id");
    if (error) return fail(dbMessage(error));
    if (!data?.length) return fail("Student not found or not permitted.");
    revalidatePath(`/admin/students/${id}`);
    return success("Photo removed.");
  });
}
