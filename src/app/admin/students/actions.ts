"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { z } from "zod";
import { withRole } from "@/lib/actions";
import { dbMessage, fail, formValues, zodFail, type FormState } from "@/lib/forms";
import { ALL_STAFF, isCentral } from "@/lib/roles";
import { optDate, optEmail, optText, reqText, uuid } from "@/lib/schemas";

const idPattern = /^[A-Z0-9-]{3,20}$/;
const optIdent = (label: string) =>
  z
    .string()
    .optional()
    .transform((v) => (v ? v.trim().toUpperCase() : ""))
    .refine((v) => v === "" || idPattern.test(v), `${label}: 3–20 letters, digits or dashes`);

const schema = z.object({
  institute_id: uuid("Institute"),
  course_id: uuid("Course"),
  session_id: uuid("Session"),
  roll_no: optIdent("Roll number"),
  registration_no: optIdent("Registration number"),
  name_en: reqText("Name (English)", 120),
  name_bn: optText,
  father_name: optText,
  mother_name: optText,
  date_of_birth: optDate,
  gender: z.enum(["male", "female", "other", ""]).optional().transform((v) => (v ? v : null)),
  phone: optText,
  email: optEmail,
  address: optText,
  national_id: optText,
  status: z.enum(["active", "completed", "dropped"]),
});

export async function saveStudent(id: string | null, _prev: FormState, formData: FormData): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase, profile }) => {
    const values = formValues(formData);
    // Tenants can only ever write to their own institute.
    if (!isCentral(profile.role)) values.institute_id = profile.institute_id ?? "";
    const parsed = schema.safeParse(values);
    if (!parsed.success) return zodFail(parsed.error, values);
    const { roll_no, registration_no, ...rest } = parsed.data;
    if (id && (!roll_no || !registration_no)) {
      return fail("Roll and registration numbers cannot be blank.", values, {
        ...(roll_no ? {} : { roll_no: "Required" }),
        ...(registration_no ? {} : { registration_no: "Required" }),
      });
    }
    // On create, blank identifiers are generated by the database
    // (roll: sequence default; registration: random, via trigger).
    const row = { ...rest, registration_no, ...(roll_no ? { roll_no } : {}) };
    const { data, error } = id
      ? await supabase.from("students").update(row).eq("id", id).select("id")
      : await supabase.from("students").insert(row).select("id");
    if (error) return fail(dbMessage(error), values);
    if (!data?.length) return fail("Student not found or not permitted.", values);
    revalidatePath("/admin/students");
    redirect(`/admin/students/${data[0].id}?saved=1`);
  });
}

export async function deleteStudent(id: string, _prev: FormState): Promise<FormState> {
  return withRole(ALL_STAFF, async ({ supabase }) => {
    const { data, error } = await supabase.from("students").delete().eq("id", id).select("id");
    if (error) return fail(dbMessage(error));
    if (!data?.length) return fail("Not permitted or student not found.");
    revalidatePath("/admin/students");
    redirect("/admin/students?deleted=1");
  });
}
