import "server-only";
import { cookies } from "next/headers";

export type Locale = "en" | "bn";
export const LOCALE_COOKIE = "lang";
export const DEFAULT_LOCALE: Locale = "bn";

export async function getLocale(): Promise<Locale> {
  const value = (await cookies()).get(LOCALE_COOKIE)?.value;
  return value === "en" || value === "bn" ? value : DEFAULT_LOCALE;
}

/** Bilingual CMS fields: prefer the requested language, fall back to English. */
export function pick(locale: Locale, en: string | null | undefined, bn: string | null | undefined) {
  return (locale === "bn" && bn ? bn : en) ?? "";
}

